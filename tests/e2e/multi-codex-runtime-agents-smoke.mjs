import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { execFile as execFileCallback } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import {
  api,
  buildServer,
  confirmBriefAndSelectWorkflow,
  createPublishedAgentWorkflow,
  createSessionAndWaitForBrief,
  listEvents,
  startSmokeServer,
  stopSmokeServer,
  waitForStatus
} from './smoke-server.mjs';

await buildServer();
const execFile = promisify(execFileCallback);

let server;
let workspaceRoot;
let worktreeRoot;

try {
  worktreeRoot = join(tmpdir(), `ac-wt-m-${process.pid}-${Date.now()}`);
  workspaceRoot = await mkdtemp(join(tmpdir(), 'agent-cluster-multi-codex-'));
  await mkdir(join(workspaceRoot, 'src'), { recursive: true });
  await writeFile(
    join(workspaceRoot, 'package.json'),
    JSON.stringify({ scripts: { test: 'node test-smoke.mjs' } }, null, 2)
  );
  await writeFile(join(workspaceRoot, 'src', 'frontend.txt'), 'frontend before\n');
  await writeFile(join(workspaceRoot, 'src', 'backend.txt'), 'backend before\n');
  await writeFile(
    join(workspaceRoot, 'test-smoke.mjs'),
    [
      "import { existsSync } from 'node:fs';",
      "console.log('multi codex tests passed');",
      "if (!existsSync('src/frontend.txt')) throw new Error('frontend file missing');",
      "if (!existsSync('src/backend.txt')) throw new Error('backend file missing');"
    ].join('\n')
  );

  const stubScript = join(workspaceRoot, 'codex-multi-stub.mjs');
  const stubCommand = join(workspaceRoot, process.platform === 'win32' ? 'codex-multi-stub.cmd' : 'codex-multi-stub.sh');
  await writeFile(
    stubScript,
    [
      "import { mkdirSync, writeFileSync } from 'node:fs';",
      "const prompt = process.argv.slice(2).join(' ');",
      "const requiredKind = process.env.AGENT_CLUSTER_EXPECTED_OUTPUT_KIND ?? prompt.match(/Required output kind:\\s*([a-z_]+)/i)?.[1] ?? prompt.match(/expectedOutput[\\s\\S]{0,240}(task_acceptance_decision|task_execution_result)/i)?.[1] ?? 'task_execution_result';",
      "const isClaim = requiredKind === 'task_acceptance_decision';",
      "const currentTaskWindow = (prompt.match(/currentTask[\\s\\S]{0,1400}/i)?.[0] ?? prompt);",
      "const agentKey = process.env.AGENT_CLUSTER_AGENT_KEY ?? '';",
      "const isFrontend = agentKey === 'frontend' || /Frontend implementation/i.test(currentTaskWindow) || /key\\s*:?\\s*frontend/i.test(currentTaskWindow);",
      "const agentName = isFrontend ? 'frontend' : 'backend';",
      "if (requiredKind === 'task_brief') {",
      "  console.log(JSON.stringify({ schemaVersion: '1.0', kind: 'task_brief', goal: 'Run frontend and backend Codex workflow nodes.', scope: [], outOfScope: [], constraints: [], acceptanceCriteria: [], risks: [], openQuestions: [], suggestedTasks: [] }));",
      "} else if (requiredKind === 'post_review_report') {",
      "  console.log(JSON.stringify({ schemaVersion: '1.0', kind: 'post_review_report', isConsistentWithBrief: true, matchedItems: [], mismatchedItems: [], missingItems: [], outOfScopeChanges: [], testResults: [], recommendation: 'deliver', actions: [] }));",
      "} else if (requiredKind === 'final_delivery') {",
      "  console.log(JSON.stringify({ schemaVersion: '1.0', kind: 'final_delivery', summary: 'Frontend and backend Codex workflow completed.', completedItems: [], incompleteItems: [], risks: [], artifactRefs: [] }));",
      "} else if (requiredKind === 'agent_message') {",
      "  console.log(JSON.stringify({ schemaVersion: '1.0', kind: 'agent_message', messageKind: 'summary', content: 'Codex workflow phase completed.', targetAgentIds: [], targetAgentKeys: [], mentionedAgentIds: [], relatedTaskIds: [] }));",
      '} else if (isClaim) {',
      '  console.log(JSON.stringify({',
      "    schemaVersion: '1.0',",
      "    kind: 'task_acceptance_decision',",
      "    status: 'accepted',",
      "    reason: `${agentName} Codex runtime accepts this coding task.`,",
      '    missingContext: [],',
      '    requestedContext: null,',
      '    handoffSuggestion: null,',
      '    confidence: 0.94,',
      "    alternativeAgentKeys: [],",
      '    alternativeAgentIds: [],',
      "    agentMessages: [{ schemaVersion: '1.0', kind: 'agent_message', messageKind: 'decision', content: `${agentName} accepts and will edit source files.`, targetAgentIds: [], targetAgentKeys: ['coordinator'], mentionedAgentIds: [], relatedTaskIds: [] }]",
      '  }));',
      '} else {',
      "  mkdirSync('src', { recursive: true });",
      "  const file = isFrontend ? 'src/frontend.txt' : 'src/backend.txt';",
      "  const generated = isFrontend ? 'src/frontend-generated.txt' : 'src/backend-generated.txt';",
      "  writeFileSync(file, `${agentName} after real codex runtime\\n`);",
      "  writeFileSync(generated, `generated by ${agentName} codex runtime\\n`);",
      '  console.log(JSON.stringify({',
      "    schemaVersion: '1.0',",
      "    kind: 'task_execution_result',",
      "    status: 'completed',",
      "    summary: `${agentName} Codex runtime edited real files on disk.`,",
      "    completedItems: [`${agentName} changed source files`],",
      '    changedArtifacts: [],',
      '    requestedContext: null,',
      "    agentMessages: [{ schemaVersion: '1.0', kind: 'agent_message', messageKind: 'progress', content: `${agentName} requests peer review for the captured source diff.`, targetAgentIds: [], targetAgentKeys: ['review', 'test'], mentionedAgentIds: [], relatedTaskIds: [] }],",
      "    nextSuggestedActions: ['Inspect captured fileChanges and test report'],",
      '    risks: []',
      '  }));',
      '}'
    ].join('\n')
  );
  if (process.platform === 'win32') {
    await writeFile(stubCommand, `@echo off\r\nnode "%~dp0codex-multi-stub.mjs" %*\r\n`);
  } else {
    await writeFile(stubCommand, `#!/bin/sh\nnode "$(dirname "$0")/codex-multi-stub.mjs" "$@"\n`);
  }
  await execFile('git', ['init'], { cwd: workspaceRoot });
  await execFile('git', ['config', 'user.email', 'multi-codex@example.invalid'], { cwd: workspaceRoot });
  await execFile('git', ['config', 'user.name', 'Multi Codex'], { cwd: workspaceRoot });
  await execFile('git', ['add', '.'], { cwd: workspaceRoot });
  await execFile('git', ['commit', '-m', 'initial fixture'], { cwd: workspaceRoot });

  server = await startSmokeServer('multi-codex-runtime-agents-smoke', {
    DISCUSSION_MAX_ROUNDS: '0',
    MOCK_PARALLEL_TASKS: 'true',
    MOCK_DECLINE_FRONTEND_TASK: 'false',
    REQUIRE_USER_CONFIRMATION: 'false',
    CODEX_RUNTIME_ENABLED: 'true',
    CODEX_RUNTIME_COMMAND: 'node',
    CODEX_RUNTIME_ARGS_JSON: JSON.stringify([stubScript]),
    CODEX_RUNTIME_PROMPT_MODE: 'file',
    CODEX_RUNTIME_SHELL: 'false',
    RUNTIME_STREAMING: 'off',
    CODEX_RUNTIME_TEST_COMMAND: 'npm test',
    AGENT_CLUSTER_WORKTREE_ROOT: worktreeRoot
  });

  const workflow = await createPublishedAgentWorkflow(
    server.apiBase,
    'Multiple Codex runtime agents workflow',
    ['frontend', 'backend']
  );

  const { sessionId, briefId } = await createSessionAndWaitForBrief(
    server.apiBase,
    'Implement frontend and backend code changes with multiple Codex coding agents, communicate with reviewers, run tests, and expose diffs.',
    {
      agentIds: ['coordinator', 'requirements', 'architect', 'frontend', 'backend', 'test', 'review', 'notification'],
      workingDirectory: {
        kind: 'server_local',
        id: '00000000-0000-0000-0000-00000000c0de',
        name: 'multi-codex-workspace',
        path: workspaceRoot,
        selectedAt: new Date().toISOString()
      },
      runtimePreference: { preferredRuntimeType: 'codex', allowedRuntimeTypes: ['codex'] }
    }
  );
  await confirmBriefAndSelectWorkflow(server.apiBase, sessionId, briefId, workflow);
  await waitForStatus(server.apiBase, sessionId, 'COMPLETED', 90_000);

  const events = await listEvents(server.apiBase, sessionId);
  const eventDebug = () =>
    JSON.stringify(
      events
        .filter((event) =>
          ['task_created', 'task_claimed', 'task_started', 'runtime_completed', 'runtime_failed', 'artifact_created'].includes(
            event.type
          )
        )
        .map((event) => ({
          type: event.type,
          taskId: event.taskId,
          fromAgentId: event.fromAgentId,
          runtimeType: event.metadata.payload?.runtimeType,
          title: event.metadata.payload?.title,
          summary: event.metadata.payload?.contentSummary,
          observedChanges: (event.metadata.payload?.systemEvidence?.workspaceChangeSet?.changes ?? []).map((item) => ({
            path: item.path,
            operation: item.operation
          })),
          message: event.metadata.payload?.message
        })),
      null,
      2
    );
  const codexCompletions = events.filter(
    (event) => event.type === 'runtime_completed' && event.metadata.payload?.runtimeType === 'codex'
  );
  const codexTaskIds = new Set(codexCompletions.map((event) => event.taskId).filter(Boolean));
  if (codexTaskIds.size < 2) {
    throw new Error(`Expected at least two Codex coding tasks, got ${codexTaskIds.size}. Events: ${eventDebug()}`);
  }

  const acceptedClaims = events.filter(
    (event) =>
      event.type === 'agent_message' &&
      event.metadata.payload?.phase === 'task_acceptance_decision' &&
      event.metadata.payload?.acceptanceDecision?.status === 'accepted'
  );
  if (acceptedClaims.length < 2) {
    throw new Error(`Expected two task acceptance decisions, got ${acceptedClaims.length}`);
  }

  const runtimeCommunications = events.filter(
    (event) => event.type === 'agent_message' && event.metadata.payload?.phase === 'agent_runtime_communication'
  );
  if (runtimeCommunications.length < 2) {
    throw new Error(`Expected both coding agents to communicate during runtime, got ${runtimeCommunications.length}`);
  }

  const fileChanges = events
    .filter((event) => event.type === 'artifact_created' && codexTaskIds.has(event.taskId))
    .flatMap((event) => event.metadata.payload?.systemEvidence?.workspaceChangeSet?.changes ?? []);
  for (const path of ['src/frontend.txt', 'src/backend.txt', 'src/frontend-generated.txt', 'src/backend-generated.txt']) {
    const change = fileChanges.find((item) => item.path === path);
    if (!change) {
      throw new Error(
        `Expected captured actual filesystem change for ${path}. Captured changes: ${JSON.stringify(
          fileChanges.map((item) => ({ path: item.path, operation: item.operation })),
          null,
          2
        )}\nEvents: ${eventDebug()}`
      );
    }
  }

  const verifiedTestGroups = events.filter(
    (event) => event.type === 'artifact_created' && codexTaskIds.has(event.taskId)
  ).filter((event) =>
    (event.metadata.payload?.systemEvidence?.verifiedTestResults ?? []).some((result) => result.status === 'passed')
  );
  if (verifiedTestGroups.length < 2) {
    const invocations = await api(server.apiBase, `/sessions/${sessionId}/debug/runtime-invocations`);
    throw new Error(
      `Expected platform-verified test evidence for each Codex coding task, got ${verifiedTestGroups.length}: ${JSON.stringify(
        {
          artifacts: events
            .filter((event) => event.type === 'artifact_created' && codexTaskIds.has(event.taskId))
            .map((event) => ({ taskId: event.taskId, systemEvidence: event.metadata.payload?.systemEvidence })),
          invocations: invocations.data.items.filter((item) => codexTaskIds.has(item.taskId))
        },
        null,
        2
      )}`
    );
  }

  const frontendFile = await readFile(join(workspaceRoot, 'src', 'frontend.txt'), 'utf8');
  const backendFile = await readFile(join(workspaceRoot, 'src', 'backend.txt'), 'utf8');
  if (frontendFile !== 'frontend before\n' || backendFile !== 'backend before\n') {
    throw new Error('Managed Codex worktrees must not directly mutate the selected source workspace.');
  }

  console.log('multi codex runtime agents smoke ok');
} finally {
  if (server) {
    await stopSmokeServer(server);
  }
  if (workspaceRoot) {
    await rm(workspaceRoot, { recursive: true, force: true });
  }
  if (worktreeRoot) {
    await rm(worktreeRoot, { recursive: true, force: true });
  }
}
